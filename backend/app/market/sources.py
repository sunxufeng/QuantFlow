"""行情数据源抽象（M2 数据层）。

设计目标（对齐开发计划 §4.2 数据层）：
- 多数据源适配：tushare 等商业源 + 明确标记的合成测试数据
- 统一返回 ``Bar`` 列表，服务层负责缓存与落库
- 生产数据源失败时显式报错，不把测试数据冒充真实行情
"""

from __future__ import annotations

import abc
import hashlib
import logging
import random
from typing import List, Optional, Tuple

